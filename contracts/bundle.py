"""Bundle the OpenAPI document and every schema file into one self-contained document.

Each schema file becomes components.schemas.<title>, and every $ref to a file, whether in the
OpenAPI document or inside another schema, is rewritten to point there. Go generation reads the
bundle so nested references become named types instead of anonymous copies.

Usage: python contracts/bundle.py OUTPUT
"""

import json
import sys
from pathlib import Path, PurePosixPath

import yaml

CONTRACTS = Path(__file__).parent
SCHEMAS = CONTRACTS / "schemas"
OPENAPI = CONTRACTS / "openapi" / "muistamo.v1.yaml"


def main(output: Path) -> None:
    files = sorted(SCHEMAS.rglob("*.json"))
    loaded = {path.resolve(): json.loads(path.read_text(encoding="utf-8")) for path in files}
    names = {path: schema["title"] for path, schema in loaded.items()}
    if len(set(names.values())) != len(names):
        raise SystemExit("schema titles must be unique: they become component names")

    components = {}
    for path, schema in loaded.items():
        body = {k: v for k, v in schema.items() if k not in ("$schema", "$id")}
        components[names[path]] = rewrite(body, path.parent, names)

    document = yaml.safe_load(OPENAPI.read_text(encoding="utf-8"))
    document = rewrite(document, OPENAPI.parent, names)
    document.setdefault("components", {})["schemas"] = dict(sorted(components.items()))

    output.parent.mkdir(parents=True, exist_ok=True)
    header = "# GENERATED by contracts/bundle.py from contracts/openapi and contracts/schemas.\n"
    output.write_text(header + yaml.safe_dump(document, sort_keys=False), encoding="utf-8")


def rewrite(node, base: Path, names: dict[Path, str]):
    if isinstance(node, dict):
        out = {}
        for key, value in node.items():
            if key == "$ref" and isinstance(value, str) and not value.startswith("#"):
                target = (base / PurePosixPath(value)).resolve()
                if target not in names:
                    raise SystemExit(f"unresolved $ref {value!r} from {base}")
                value = f"#/components/schemas/{names[target]}"
            out[key] = rewrite(value, base, names)
        return out
    if isinstance(node, list):
        return [rewrite(item, base, names) for item in node]
    return node


if __name__ == "__main__":
    main(Path(sys.argv[1]))
